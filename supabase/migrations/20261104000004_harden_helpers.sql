-- rls_auto_enable() создаёт сам Supabase, если при создании проекта включена
-- опция «автоматически включать RLS». Это функция событийного триггера:
-- вызывать её через API никому не нужно, а по умолчанию её мог вызвать даже anon.
-- Событийный триггер продолжит работать — EXECUTE на него не влияет.
do $$
begin
  if to_regprocedure('public.rls_auto_enable()') is not null then
    revoke execute on function public.rls_auto_enable() from public, anon, authenticated;
  end if;
end $$;

